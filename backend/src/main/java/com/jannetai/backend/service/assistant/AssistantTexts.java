    private AssistantTexts() {
    }

    /** EN, HI, MR, BN, TA, TE or KN; anything else (or null) is EN. */
    public static String language(String code) {
        String upper = code == null ? "EN" : code.trim().toUpperCase(Locale.ROOT);
        return LANGUAGES.contains(upper) ? upper : "EN";
    }

    public static String get(String key, String language, Object... args) {
        Map<String, String> byLang = TEXTS.get(key);
        if (byLang == null) {
            throw new IllegalArgumentException("Unknown assistant text: " + key);
        }
        String text = byLang.getOrDefault(language(language), byLang.get("EN"));
        for (int i = 0; i < args.length; i++) {
            text = text.replace("{" + i + "}", String.valueOf(args[i]));
        }
        return text;
    }

    public static String statusLabel(ComplaintStatus status, String language) {
        return get("label_" + status.name(), language);
    }

    public static String statusExplanation(ComplaintStatus status, String language, String reason) {
        String key = "status_" + status.name();
        if (!TEXTS.containsKey(key)) {
            key = "status_OTHER";
        }
        return get(key, language, reason == null ? "" : reason);
    }

    public static String rejectionReason(String code, String language) {
        String key = "reason_" + (code == null ? "UNKNOWN" : code);
        return get(TEXTS.containsKey(key) ? key : "reason_UNKNOWN", language);
    }

    public static String category(ComplaintCategory category, String language) {
        return get("category_" + (category == null ? ComplaintCategory.GENERAL : category).name(), language);
    }

    /** The chip texts of one key in every language (the router recognises a tapped chip exactly). */
    public static Map<String, String> allLanguages(String key) {
        return TEXTS.get(key);
    }

    static Set<String> keys() {
        return TEXTS.keySet();
    }
